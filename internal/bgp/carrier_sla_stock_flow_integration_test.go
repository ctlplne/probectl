type stockCarrierSLAFlow struct {
	Key     string `json:"key"`
	Bytes   string `json:"observed_bytes"`
	Packets string `json:"observed_packets"`
	StartNS string `json:"start_ns"`
	EndNS   string `json:"end_ns"`
}

func proveStockCarrierSLAFlow(t *testing.T, st *shipped.Stack, lab *routingLab, primary, paired edgeFlowRegistration,
	link roleRouterLink, routerIP, pairedDestination, image, fingerprint string) {
	t.Helper()
	installRouterLabHostRoute(t, link.peerIP, routerIP)
	pairedLink := link
	pairedLink.name += "-sla-paired"
	pairedExporter := startRoleRouterExporter(t, lab, image, pairedDestination, pairedLink, "icmp")
	registrations := [2]edgeFlowRegistration{primary, paired}
	exporters := [2]string{lab.name + "-" + link.name + "-flow", pairedExporter}
	var probes [2]routerChangeProbe
	probeStart := time.Now().UTC()
	for i, reg := range registrations {
		probes[i] = startRouterChangeProbe(t, st, reg, link.peerIP, "carrier-sla-"+strconv.Itoa(i))
	}
	pool := st.ApplicationReadPool(t)
	var originals [2]stockCarrierSLAFlow
	for i, reg := range registrations {
		awaitRouterChangeProbe(t, st, reg, probes[i], probeStart)
		// Keep the authentic receipts and the issued identity. Stop the
		// recurring measurements before the export and report stage.
		st.Stop(t, probes[i].process)
	}
	for i, reg := range registrations {
		t.Run("raw-lane-"+strconv.Itoa(i), func(t *testing.T) {
			// delete-all does not clear a partially filled libpcap block.
			// Start a fresh ring after both probe publishers have stopped.
			exporter := exporters[i]
			lab.docker(t, "restart", "-t", "2", exporter)
			shipped.Await(t, "fresh carrier capture ring", 15*time.Second, func() bool {
				ctx, cancel := context.WithTimeout(t.Context(), 3*time.Second)
				defer cancel()
				return exec.CommandContext(ctx, "docker", "exec", exporter, "softflowctl", "-c", "/tmp/softflowd.ctl", "statistics").Run() == nil
			})
			from := time.Now().UTC().Truncate(time.Millisecond)
			emitRoleRouterCapturedTraffic(t, lab, exporter, link, link.routerIP, link.peerIP, "1", false)
			originals[i] = awaitStockCarrierSLAFlow(t, pool, reg, link, from)
		})
	}
	if t.Failed() {
		return
	}
	if originals[0].Key == originals[1].Key {
		t.Fatal("the two authenticated flow collectors shared an original capture key")
	}
	reportAt := time.Now().UTC()
	for i, reg := range registrations {
		interfaceID := awaitRoleRouterInterfaces(t, st, reg, []roleRouterLink{link})[link.index]
		artifactID, signed := stockCarrierSLADownload(t, st, reg, interfaceID, probes[i], reportAt)
		verifyStockCarrierSLAFlow(t, signed, fingerprint, reg, link.index, originals[i], originals[1-i].Key)
		if code, _ := st.Do(t, registrations[1-i].cookie, http.MethodGet, "/v1/dashboard-report-artifacts/"+artifactID, nil); code != http.StatusNotFound {
			t.Fatal("a tenant could download the sibling's signed carrier artifact", code)
		}
	}
}

// Read the actual raw input independently of the signed report. Both source
// identifiers are generated by the lab; the assertions run on the served API.
func awaitStockCarrierSLAFlow(t *testing.T, pool *pgxpool.Pool, reg edgeFlowRegistration, link roleRouterLink, from time.Time) stockCarrierSLAFlow {
	t.Helper()
	if !transferStockSQLIdentity.MatchString(reg.tenantID) || !transferStockSQLIdentity.MatchString(reg.agentID) {
		t.Fatal("invalid stock flow fixture identity")
	}
	source, sourceErr := netip.ParseAddr(link.routerIP)
	destination, destinationErr := netip.ParseAddr(link.peerIP)
	if sourceErr != nil || destinationErr != nil || !source.Is4() || !destination.Is4() {
		t.Fatal("invalid owned routed workload endpoints")
	}
	endpoints := fmt.Sprintf(`tenant_id='%s' AND agent_id='%s' AND protocol='ipfix'
 AND ((src_addr='%s' AND dst_addr='%s') OR (src_addr='%s' AND dst_addr='%s'))`,
		reg.tenantID, reg.agentID, source, destination, destination, source)
	query := fmt.Sprintf(`SELECT routing_capture_key AS key,toString(bytes) AS observed_bytes,toString(packets) AS observed_packets,
 toString(toUnixTimestamp64Nano(start_ts)) AS start_ns,toString(toUnixTimestamp64Nano(ts)) AS end_ns
 FROM probectl_flows FINAL WHERE %s
 AND (in_if=%d OR out_if=%d) AND clock_basis=%d AND length(routing_capture_key)=64
 AND toUnixTimestamp64Nano(start_ts)>=%d AND packets>0 AND bytes>0
	ORDER BY ts DESC,routing_capture_key LIMIT 64 FORMAT JSON`, endpoints, link.index, link.index,
		flowv1.FlowClockBasis_FLOW_CLOCK_BASIS_EXPORTER_INTERVAL, from.UnixNano())
	const ownershipQuery = `SELECT COALESCE((
 SELECT CASE WHEN receipt.outcome<>'captured' THEN receipt.outcome
 WHEN facts.searchable_body#>>'{data,Owner,AgentID}'=$3
  AND facts.searchable_body#>>'{data,Owner,context_id}'=$4
  AND facts.searchable_body#>>'{data,Owner,RouterID}'=$5 THEN 'owned'
 ELSE 'owner_mismatch' END
 FROM bgp_flow_capture_receipts receipt
 LEFT JOIN bgp_flow_capture_payloads links ON (links.tenant_id,links.flow_key)=(receipt.tenant_id,receipt.flow_key)
 LEFT JOIN bgp_flow_capture_objects facts ON (facts.tenant_id,facts.digest,facts.kind)=(links.tenant_id,links.facts_digest,'routing_facts')
 WHERE receipt.tenant_id=$1 AND receipt.flow_key=$2
 ),'pending')`
	var original stockCarrierSLAFlow
	var latest struct{ Data []stockCarrierSLAFlow }
	var rawErr error
	var outcomes map[string]int
	ctx := tenancy.WithTenant(t.Context(), tenancy.ID(reg.tenantID))
	ready := waitTransferStock(t, time.Minute, func() bool {
		latest.Data, outcomes = nil, nil
		body, err := shipped.CHQuery(shipped.CHURL(), query)
		if err != nil {
			rawErr = err
			return false
		}
		if rawErr = json.Unmarshal([]byte(body), &latest); rawErr != nil || len(latest.Data) == 0 {
			return false
		}
		outcomes = make(map[string]int)
		err = tenancy.InTenantReadSnapshot(ctx, pool, func(ctx context.Context, sc tenancy.Scope) error {
			for _, row := range latest.Data {
				key, err := hex.DecodeString(row.Key)
				if err != nil {
					return fmt.Errorf("decode retained stock capture key: %w", err)
				}
				if len(key) != 32 {
					return fmt.Errorf("retained stock capture key has %d bytes", len(key))
				}
				var outcome string
				if err := sc.Q.QueryRow(ctx, ownershipQuery, reg.tenantID, key, reg.agentID, reg.contextID, reg.deviceID).Scan(&outcome); err != nil {
					return err
				}
				outcomes[outcome]++
				if outcome == "owned" {
					original = row
					break
				}
			}
			return nil
		})
		if err != nil {
			t.Fatalf("read retained stock ownership with the scoped application role: %v", err)
		}
		return original.Key != ""
	})
	if !ready {
		rows, err := shipped.CHQuery(shipped.CHURL(), fmt.Sprintf(`SELECT in_if,out_if,clock_basis,length(routing_capture_key) AS key_length,
 toString(bytes) AS bytes,toString(packets) AS packets,toString(toUnixTimestamp64Nano(start_ts)) AS start_ns,
 toString(toUnixTimestamp64Nano(ts)) AS end_ns FROM probectl_flows FINAL WHERE %s
 AND toUnixTimestamp64Nano(ts)>=%d ORDER BY ts DESC LIMIT 12 FORMAT JSONEachRow`, endpoints, from.Add(-10*time.Second).UnixNano()))
		t.Fatalf("no committed owned stock flow at or after %s on interface %d (matching raw rows=%d, receipt states=%v, query error=%v): nearby rows=%s (error=%v)",
			from.Format(time.RFC3339Nano), link.index, len(latest.Data), outcomes, rawErr, strings.TrimSpace(rows), err)
	}
	return original
}

func stockCarrierSLADownload(t *testing.T, st *shipped.Stack, reg edgeFlowRegistration, interfaceID string, probe routerChangeProbe, observed time.Time) (string, []byte) {
	t.Helper()
	from := time.Date(observed.Year(), observed.Month(), 1, 0, 0, 0, 0, time.UTC)
	request := sdk.CapacityAgreementInput{Definition: sdk.CapacityAgreementDefinition{
		Name: "Stock carrier SLA", Reference: "Routed lab circuit", ValidFrom: from.Format(time.RFC3339Nano), BillingDay: 1,
		Timezone: "UTC", Direction: "in", Currency: "USD", CommitBps: "0", UnitBps: "1", UnitPrice: "0",
		Target: sdk.CapacityTarget{Kind: "interface", ContextId: reg.contextID, InterfaceId: interfaceID},
		Sla: &sdk.CarrierSLATerms{Carrier: "Lab carrier", CircuitId: "Stock routed circuit", MonthlyCharge: "100", Currency: "USD", Aggregation: "maximum", CreditCapRatio: "1",
			Sources: []sdk.CarrierSLASource{{AgentId: probe.agent, TestId: probe.test}}, Rules: []sdk.CarrierSLARule{{
				Id: "loss", Metric: "loss", Basis: "original_packet_ratio", GoodWhen: "at_most", Threshold: "0.01",
				CreditBands: []sdk.CarrierSLACreditBand{{FromInclusive: "0.01", CreditRatio: "0.1"}},
			}}},
	}}
	code, body := st.Do(t, reg.cookie, http.MethodPost, "/v1/flows/capacity/agreements", request)
	var agreement sdk.CapacityAgreement
	if code != http.StatusCreated || json.Unmarshal(body, &agreement) != nil || agreement.Id == "" || agreement.Version != "1" {
		t.Fatalf("create owned stock circuit terms: HTTP %d: %.300s", code, body)
	}
	dashboard := sdk.DashboardCreateRequest{Name: "Stock carrier claim", Preset: "operator", Definition: sdk.DashboardDefinition{
		CarrierClaim: &sdk.CarrierSLAReportDefinition{Selections: []sdk.CarrierSLAReportSelection{{AgreementId: agreement.Id, Version: agreement.Version, At: observed.Format(time.RFC3339Nano)}}},
		Provenance:   []string{"stock IPFIX and routed probe"}, RedactionState: "tenant policy", CoverageLimitations: []string{"current month incomplete"},
	}}
	code, body = st.Do(t, reg.cookie, http.MethodPost, "/v1/dashboards", dashboard)
	var view sdk.DashboardView
	if code != http.StatusCreated || json.Unmarshal(body, &view) != nil || view.Id == "" {
		t.Fatalf("create owned stock carrier report: HTTP %d: %.300s", code, body)
	}
	code, body = st.Do(t, reg.cookie, http.MethodPost, "/v1/dashboard-reports", map[string]string{"dashboard_id": view.Id, "format": "csv"})
	var artifact sdk.DashboardReportArtifact
	if code != http.StatusCreated || json.Unmarshal(body, &artifact) != nil || artifact.Id == "" {
		t.Fatalf("generate signed stock carrier report: HTTP %d: %.300s", code, body)
	}
	code, body = st.Do(t, reg.cookie, http.MethodGet, "/v1/dashboard-report-artifacts/"+artifact.Id, nil)
	if code != http.StatusOK {
		t.Fatalf("download owned signed stock carrier report: HTTP %d: %.300s", code, body)
	}
	reader := csv.NewReader(bytes.NewReader(body))
	reader.FieldsPerRecord = -1
	rows, err := reader.ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	var signed []byte
	for _, row := range rows {
		if len(row) != 6 || !strings.HasPrefix(row[0], "pkg_") {
			continue
		}
		signed, err = base64.StdEncoding.AppendDecode(signed, []byte(row[5]))
		if err != nil {
			t.Fatal("decode retained stock carrier evidence transfer", err)
		}
	}
	return artifact.Id, signed
}

func verifyStockCarrierSLAFlow(t *testing.T, signed []byte, fingerprint string, reg edgeFlowRegistration, index uint32, original stockCarrierSLAFlow, foreignKey string) {
	t.Helper()
	manifest, err := evidence.Verify(signed)
	if err != nil || manifest.Profile != "carrier-sla" {
		t.Fatal("stock carrier report failed offline verification", err)
	}
	var envelope evidence.Package
	if err := json.Unmarshal(signed, &envelope); err != nil || envelope.Signing.Fingerprint != fingerprint || len(envelope.Attachments) != 2 {
		t.Fatal("stock carrier report lost the pinned signer or original attachment", err)
	}
	var observations struct {
		Selections []struct {
			Coverage string `json:"flow_coverage"`
			Records  []struct {
				Key        string    `json:"capture_key"`
				ContextID  string    `json:"context_id"`
				RouterID   string    `json:"router_id"`
				Bytes      string    `json:"observed_bytes"`
				Packets    string    `json:"observed_packets"`
				ClockBasis string    `json:"clock_basis"`
				Start      time.Time `json:"start"`
				End        time.Time `json:"end"`
				InIf       uint32    `json:"ingress_if_index"`
				OutIf      uint32    `json:"egress_if_index"`
			} `json:"flow_records"`
		} `json:"selections"`
	}
	if err := json.Unmarshal(envelope.Attachments[1].Content, &observations); err != nil || len(observations.Selections) != 1 || observations.Selections[0].Coverage != "attested_flow_context" {
		t.Fatal("signed stock carrier report omitted attested flow context", err)
	}
	found := false
	for _, record := range observations.Selections[0].Records {
		if record.Key == foreignKey || record.ContextID != reg.contextID || record.RouterID != reg.deviceID || (record.InIf != index && record.OutIf != index) {
			t.Fatal("a signed flow crossed the owning tenant, router or selected circuit")
		}
		if record.Key == original.Key {
			if found || record.Bytes != original.Bytes || record.Packets != original.Packets || record.ClockBasis != "exporter_interval" ||
				strconv.FormatInt(record.Start.UnixNano(), 10) != original.StartNS || strconv.FormatInt(record.End.UnixNano(), 10) != original.EndNS {
				t.Fatal("signed report changed the stock exporter's original counters or clocks")
			}
			found = true
		}
	}
	if !found {
		t.Fatal("the selected original stock exporter capture was absent from the signed claim")
	}
}
