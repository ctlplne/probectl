package cipolicy

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// A script that bind-mounts the repository into a linux container and then runs
// npm installs that platform's binaries over the HOST's web/node_modules. The
// next local `npm test` dies with "Cannot find native binding", and npm's own
// message blames its optional-dependency bug rather than the script that did it
// — so the cost lands on whoever runs the CI-parity check next, not on whoever
// wrote it (DPR-267).
//
// The rule: bind-mount the repo AND run npm => isolate web/node_modules. A script
// that mounts only package.json and package-lock.json (check_web_lock.sh copies
// them into the container) never touches the host tree and is unaffected.
func TestContainerNpmScriptsIsolateNodeModules(t *testing.T) {
	t.Parallel()
	dir := filepath.Join("..", "..", "scripts")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read scripts dir: %v", err)
	}
	checked := 0
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".sh") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			t.Fatalf("read %s: %v", entry.Name(), err)
		}
		script := string(body)
		if !strings.Contains(script, "docker run") || !strings.Contains(script, "npm") {
			continue
		}
		// Does it bind-mount a directory (not a single file) that contains web/?
		mountsTree := strings.Contains(script, `-v "$repo_root:`) ||
			strings.Contains(script, `--volume "$ROOT:`) ||
			strings.Contains(script, `--volume "$repo_root:`) ||
			strings.Contains(script, `-v "$ROOT:`)
		if !mountsTree {
			continue
		}
		checked++
		// The FLAG, on a line that is not a comment. Matching the words anywhere in
		// the file passed on the explanatory comment above the fix — this test's own
		// first version did exactly that and survived its bisect.
		var isolated bool
		for _, line := range strings.Split(script, "\n") {
			if strings.HasPrefix(strings.TrimSpace(line), "#") {
				continue
			}
			if strings.Contains(line, "--tmpfs") && strings.Contains(line, "node_modules") {
				isolated = true
				break
			}
		}
		if !isolated {
			t.Errorf("scripts/%s bind-mounts the repository and runs npm without a tmpfs over web/node_modules, so a container install overwrites the host's with the container platform's binaries", entry.Name())
		}
	}
	// Non-vacuity: at least the two known container npm scripts must be examined,
	// or a rename would turn this test into a no-op.
	if checked < 2 {
		t.Fatalf("examined only %d container npm script(s); the detection no longer matches how they mount the repo", checked)
	}
}
