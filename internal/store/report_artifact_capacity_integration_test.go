type reportCapacityFill byte

func (b reportCapacityFill) Read(p []byte) (int, error) {
	for i := range p {
		p[i] = byte(b)
	}
	return len(p), nil
}

// These are complete real Postgres bodies, not allocation-only declarations.
// Identical artifact IDs in two tenant lanes retain different independent bytes.
func TestReportArtifactConfiguredCapacityBeyondFormerBodyCeiling(t *testing.T) {
	ctx := t.Context()
	pool := setup(ctx, t)
	t.Cleanup(pool.Close)
	const size int64 = (256 << 20) + reporting.BodyChunkBytes
	limits := reporting.BodyStageLimits{Bytes: size, MemoryBytes: size + (size/reporting.BodyChunkBytes)*64 + 256<<10}
	tenants := make([]string, 0, 2)
	digests := make([][]byte, 0, 2)
	t.Cleanup(func() {
		if _, err := pool.Exec(context.Background(), "DELETE FROM tenants WHERE id=ANY($1::uuid[])", tenants); err != nil {
			t.Error(err)
		}
	})
	for lane := range 2 {
		tenant, err := NewTenants(pool).Create(ctx, fmt.Sprintf("report-capacity-%d-%d", lane, time.Now().UnixNano()), "Report capacity")
		if err != nil {
			t.Fatal(err)
		}
		tenants = append(tenants, tenant.ID)
		owned := tenancy.WithTenant(ctx, tenancy.ID(tenant.ID))
		contents := reportCapacityFill('A' + lane)
		digest, err := crypto.HashReader(io.LimitReader(contents, size))
		if err != nil {
			t.Fatal(err)
		}
		stage, receipt, err := reporting.StageBody(owned, tenant.ID, limits, func(w io.Writer) error {
			n, err := io.CopyN(w, contents, size)
			if err == nil && n != size {
				return io.ErrUnexpectedEOF
			}
			return err
		})
		if err != nil {
			t.Fatal("configured body above former256MiB ceiling refused", err)
		}
		if receipt.Bytes != size || receipt.SHA256 != hex.EncodeToString(digest) {
			_ = stage.Close()
			t.Fatal("large body staging lost independently generated bytes")
		}
		capture, err := json.Marshal(map[string]any{"version": 1, "tenant_id": tenant.ID})
		if err != nil {
			_ = stage.Close()
			t.Fatal(err)
		}
		err = tenancy.InTenant(owned, pool, func(ctx context.Context, sc tenancy.Scope) error {
			if _, err := (DashboardReports{}).CreateView(ctx, sc, DashboardViewInput{ID: "same-view", OwnerID: "alice", Name: "Capacity", Preset: "operator", Definition: []byte("{}")}); err != nil {
				return err
			}
			input := ReportArtifactInput{ID: "same-capacity-body", DashboardID: "same-view", Format: "csv", MediaType: "text/csv", Filename: "capacity.csv", GeneratedBy: "alice",
				AbsoluteFrom: time.Now().Add(-time.Hour), AbsoluteTo: time.Now(), RedactionState: "none",
				Provenance: []string{"generated capacity component"}, CoverageLimitations: []string{"seeded storage component"}}
			_, err := (DashboardReports{}).CreateChunkedArtifact(ctx, sc, input, stage, capture)
			return err
		})
		_ = stage.Close()
		if err != nil {
			t.Fatal("configured large body publication failed", err)
		}
		digests = append(digests, digest)
	}
	// Both complete foreign bodies now exist before either read is checked.
	for lane, tenant := range tenants {
		owned := tenancy.WithTenant(ctx, tenancy.ID(tenant))
		digest := digests[lane]
		var restored *reporting.BodyStage
		err := tenancy.InTenantReadSnapshot(owned, pool, func(ctx context.Context, sc tenancy.Scope) error {
			var metadata *ReportArtifactMetadata
			var err error
			metadata, restored, err = (DashboardReports{}).StageArtifactBody(ctx, sc, "same-capacity-body", "alice", limits)
			if err != nil {
				return err
			}
			if metadata.BodyBytes != size || metadata.BodySHA256 != hex.EncodeToString(digest) {
				t.Fatal("large stored body changed exact size or independent digest")
			}
			var foreign int
			if err := sc.Q.QueryRow(ctx, "SELECT count(*) FROM dashboard_report_artifact_chunks WHERE tenant_id<>$1", tenant).Scan(&foreign); err != nil {
				return err
			}
			if foreign != 0 {
				t.Fatal("large body chunks escaped FORCE RLS")
			}
			return nil
		})
		if restored != nil {
			t.Cleanup(func() { _ = restored.Close() })
		}
		if err != nil {
			t.Fatal("configured large body verified read failed", err)
		}
		reader, err := restored.Open(owned)
		if err != nil {
			t.Fatal(err)
		}
		actual, err := crypto.HashReader(reader)
		_ = reader.Close()
		_ = restored.Close()
		if err != nil || !bytes.Equal(actual, digest) {
			t.Fatal("large body download lost own complete content", err)
		}
		t.Logf("configured complete body lane=%d bytes=%d chunks=%d sha256=%s", lane, size, size/reporting.BodyChunkBytes, hex.EncodeToString(digest))
	}
}
