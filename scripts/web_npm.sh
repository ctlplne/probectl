#!/usr/bin/env bash
# SPDX-License-Identifier: BUSL-1.1
#
# Run an npm command for web/ inside the SAME digest-pinned Node image CI and
# deploy/docker/Dockerfile use, instead of whatever npm the host happens to have.
#
# DPR-236 / CQA-001: Node 26.12.1 and npm 11.20.0 own the lockfile.
# CI, release builds and browser tooling use the same generation. Always prove
# a fresh npm ci; a populated node_modules can conceal a broken lockfile.
#
#   scripts/web_npm.sh ci                 # install exactly what the lock says
#   scripts/web_npm.sh install --package-lock-only   # regenerate the lock
#   scripts/web_npm.sh run typecheck
#
# internal/cipolicy TestWebLockHasNoNonOptionalPlatformBinaries fails if a lock
# generated by the wrong npm is ever committed.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# The digest below is kept byte-identical to deploy/docker/Dockerfile's web stage —
# the image that builds the shipped bundle is the image that owns the lock — and it
# is a LITERAL because SUPPLY-002 requires a statically identifiable digest.
# internal/cipolicy TestWebNodeImageMatchesTheDockerfile fails if they drift.
PLATFORM="${PROBECTL_WEB_NODE_PLATFORM:-linux/amd64}"

if [ "$#" -eq 0 ]; then
  echo "usage: scripts/web_npm.sh <npm args...>" >&2
  exit 2
fi

# DPR-267: the repo is bind-mounted, so without this tmpfs a container `npm ci`
# writes linux/amd64 binaries straight over the HOST's web/node_modules. The next
# local `npm test` then dies with "Cannot find native binding" and npm's own
# message blames its optional-dependency bug rather than this script — which is
# exactly how the last run of this check cost an hour. Nothing this script is for
# (verifying the lock, regenerating the lock, running a typecheck at CI parity)
# needs the install to survive on the host, and local work uses the host npm.
# scripts/web_rendered_a11y_container.sh already isolates node_modules this way.
exec docker run --rm \
  --platform "$PLATFORM" \
  -v "$repo_root:/src" \
  --tmpfs /src/web/node_modules:rw,exec \
  -w /src/web \
  -e npm_config_update_notifier=false \
  -e HOME=/tmp \
  node:26-bookworm-slim@sha256:28147155d47dc31abe0a46e0d12b59b2fb3d0a2dcc5dc65fce76a074180b16fe \
  npm "$@"
