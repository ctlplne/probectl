type releaseTestTagProjection struct {
	Revision string `json:"tag_revision"`
	AsOf     string `json:"as_of"`
	Items    []struct {
		ContextID string `json:"context_id"`
		Kind      string `json:"target_kind"`
		ID        string `json:"target_id"`
		Revision  string `json:"tag_revision"`
		AsOf      string `json:"as_of"`
		Items     []struct {
			Key, Value, Source string
			TagID              string `json:"tag_id"`
		} `json:"items"`
	} `json:"items"`
}

type releaseTestTagLane struct {
	api                             api
	objects                         tenantObjects
	contextID, definitionID, ruleID string
	ruleValue, manualValue, pattern string
}

// This is a release-image/production-auth API and real-CLI fragment. It does
// not attest a result's sender/test ID, SNMP evidence, browser, report artifact
// or the whole feature. TestE2E retains its independent live agent/bus proofs.
func proveReleaseTestTagMetadata(t *testing.T, root, work, ca string, a, b api, objA, objB tenantObjects) {
	t.Helper()
	binary := filepath.Join(work, "probectl-test-tag-cli")
	runCmd(t, root, nil, "go", "build", "-o", binary, "./cmd/probectl")
	lanes := []releaseTestTagLane{{api: a, objects: objA}, {api: b, objects: objB}}
	for i := range lanes {
		lane := &lanes[i]
		var context struct {
			ContextID string `json:"context_id"`
			TenantID  string `json:"tenant_id"`
		}
		lane.api.json(t, http.StatusCreated, http.MethodPost, "/v1/entity-contexts", map[string]string{
			"site_label": "same test site", "vrf_label": "same test VRF",
		}, &context)
		if context.ContextID == "" || context.TenantID != lane.objects.tenant {
			t.Fatal("release context is missing its owned tenant identity")
		}
		lane.contextID = context.ContextID
		lane.api.json(t, http.StatusOK, http.MethodPut, "/v1/tests/"+lane.objects.testID+"/entity-context",
			map[string]string{"context_id": lane.contextID}, nil)
		var definition struct {
			ID string `json:"id"`
		}
		lane.api.json(t, http.StatusCreated, http.MethodPost, "/v1/tags", map[string]string{"key": "test_customer"}, &definition)
		if definition.ID == "" {
			t.Fatal("release tag definition has no ID")
		}
		lane.definitionID = definition.ID
		lane.ruleValue = "rule-" + lane.objects.tenant + " 🌐 العربية e\u0301 " + strings.Repeat("界", 1024)
		lane.manualValue = "manual-" + lane.objects.tenant + " 🌐 עברית"
		// Marks are generated by this test from fixed hexadecimal text.
		lane.pattern = "^" + lane.objects.mark + "-test$"
		var rule struct {
			ID string `json:"id"`
		}
		lane.api.json(t, http.StatusCreated, http.MethodPost, "/v1/entity-contexts/"+lane.contextID+"/tag-rules", lane.ruleInput(), &rule)
		if rule.ID == "" {
			t.Fatal("release tag rule has no ID")
		}
		lane.ruleID = rule.ID
	}
	if lanes[0].contextID == lanes[1].contextID || lanes[0].definitionID == lanes[1].definitionID {
		t.Fatal("same labels/keys collapsed the release tenants' identities")
	}
	for i := range lanes {
		lane, foreign := &lanes[i], &lanes[1-i]
		input := map[string]any{"test_ids": []string{lane.objects.testID, foreign.objects.testID, lane.objects.testID}}
		initial := lane.read(t, input)
		assertReleaseTestTagProjection(t, initial, *lane, lane.ruleValue, "rule")
		fromCLI := runReleaseTestTagCLI(t, binary, work, ca, *lane, input)
		assertReleaseTestTagProjection(t, fromCLI, *lane, lane.ruleValue, "rule")
		if fromCLI.Revision != initial.Revision {
			t.Fatal("CLI changed the exact current metadata revision")
		}
		previous := lane.ruleValue
		lane.ruleValue += " changed"
		lane.api.json(t, http.StatusOK, http.MethodPut, "/v1/entity-contexts/"+lane.contextID+"/tag-rules/"+lane.ruleID, lane.ruleInput(), nil)
		edited := lane.read(t, input)
		assertReleaseTestTagProjection(t, edited, *lane, lane.ruleValue, "rule")
		before, errBefore := strconv.ParseUint(initial.Revision, 10, 64)
		after, errAfter := strconv.ParseUint(edited.Revision, 10, 64)
		if errBefore != nil || errAfter != nil || after <= before || initial.Items[0].Items[0].Value != previous {
			t.Fatal("release rule edit lost its revision or frozen earlier response")
		}
		var assignment struct {
			ID string `json:"id"`
		}
		lane.api.json(t, http.StatusCreated, http.MethodPost, "/v1/entity-contexts/"+lane.contextID+"/tag-assignments", map[string]string{
			"tag_id": lane.definitionID, "target_kind": "test", "target_id": lane.objects.testID, "value": lane.manualValue,
		}, &assignment)
		if assignment.ID == "" {
			t.Fatal("release manual test assignment has no ID")
		}
		assertReleaseTestTagProjection(t, lane.read(t, input), *lane, lane.manualValue, "manual")
		lane.ruleValue += " beneath override"
		lane.api.json(t, http.StatusOK, http.MethodPut, "/v1/entity-contexts/"+lane.contextID+"/tag-rules/"+lane.ruleID, lane.ruleInput(), nil)
		assertReleaseTestTagProjection(t, lane.read(t, input), *lane, lane.manualValue, "manual")
		code, _ := lane.api.do(t, http.MethodDelete, "/v1/entity-contexts/"+lane.contextID+"/tag-assignments/"+assignment.ID, nil)
		if code != http.StatusNoContent {
			t.Fatal("release manual override could not be explicitly reset", code)
		}
		assertReleaseTestTagProjection(t, runReleaseTestTagCLI(t, binary, work, ca, *lane, input), *lane, lane.ruleValue, "rule")
		for _, attempt := range []struct {
			method, path string
			body         any
			want         int
		}{
			{http.MethodPost, "/v1/entity-contexts/" + foreign.contextID + "/tag-rules", lane.ruleInput(), http.StatusNotFound},
			{http.MethodPut, "/v1/tests/" + foreign.objects.testID + "/entity-context", map[string]string{"context_id": lane.contextID}, http.StatusConflict},
			{http.MethodPut, "/v1/entity-contexts/" + foreign.contextID + "/tag-rules/" + foreign.ruleID, lane.ruleInput(), http.StatusNotFound},
			{http.MethodDelete, "/v1/tags/" + foreign.definitionID, nil, http.StatusNotFound},
		} {
			code, _ := lane.api.do(t, attempt.method, attempt.path, attempt.body)
			if code != attempt.want {
				t.Fatal("foreign release metadata write did not preserve its fail-closed status", attempt.method, code)
			}
		}
		assertReleaseTestTagProjection(t, foreign.read(t, map[string]any{"test_ids": []string{foreign.objects.testID, lane.objects.testID}}), *foreign, foreign.ruleValue, "rule")
	}
	t.Log("release paired test metadata API/CLI: exact owned IDs, Unicode, revisions, rule changes, manual precedence/reset and foreign write refusals passed")
}

func (l releaseTestTagLane) ruleInput() map[string]any {
	return map[string]any{"tag_id": l.definitionID, "target_kind": "test", "match_kind": "name_pattern", "name_pattern": l.pattern, "value": l.ruleValue, "priority": 0}
}

func (l releaseTestTagLane) read(t *testing.T, input any) releaseTestTagProjection {
	t.Helper()
	var out releaseTestTagProjection
	l.api.json(t, http.StatusOK, http.MethodPost, "/v1/tags/tests/resolve", input, &out)
	return out
}

func assertReleaseTestTagProjection(t *testing.T, out releaseTestTagProjection, lane releaseTestTagLane, value, source string) {
	t.Helper()
	if len(out.Items) != 1 || out.Revision == "" {
		t.Fatal("release test metadata retained a foreign/duplicate target or lost its revision")
	}
	clock, err := time.Parse(time.RFC3339Nano, out.AsOf)
	if err != nil || clock.IsZero() {
		t.Fatal("release test metadata lost its captured as_of")
	}
	item := out.Items[0]
	if item.ID != lane.objects.testID || item.ContextID != lane.contextID || item.Kind != "test" || item.Revision != out.Revision || item.AsOf != out.AsOf || len(item.Items) != 1 {
		t.Fatal("release test metadata changed the owned identity, clock or exact result set")
	}
	tag := item.Items[0]
	if tag.TagID != lane.definitionID || tag.Key != "test_customer" || tag.Value != value || tag.Source != source {
		t.Fatal("release test metadata lost complete Unicode, source or immutable field identity")
	}
}

func runReleaseTestTagCLI(t *testing.T, binary, work, ca string, lane releaseTestTagLane, input any) releaseTestTagProjection {
	t.Helper()
	encoded, err := json.Marshal(input)
	if err != nil {
		t.Fatal("encode release CLI metadata input")
	}
	bodyPath := filepath.Join(work, "test-tags-"+lane.objects.tenant+".json")
	if err := os.WriteFile(bodyPath, encoded, 0o600); err != nil {
		t.Fatal("write owned release CLI metadata input")
	}
	command := exec.CommandContext(t.Context(), binary, "--json", "tags", "tests", "--body-file", bodyPath)
	command.Env = append(os.Environ(), "PROBECTL_API_URL="+lane.api.base, "PROBECTL_API_TOKEN="+lane.api.token, "PROBECTL_CA_FILE="+ca, "PROBECTL_TENANT="+lane.objects.tenant)
	var output bytes.Buffer
	command.Stdout = &output
	// Keep credentials and response bodies out of command/error logging.
	if err := command.Run(); err != nil {
		t.Fatal("release metadata CLI failed with verified HTTPS and private credential environment", err)
	}
	var result releaseTestTagProjection
	if err := json.Unmarshal(output.Bytes(), &result); err != nil {
		t.Fatal("release metadata CLI returned an invalid projection")
	}
	return result
}
