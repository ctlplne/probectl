const pseudo: Record<MessageKey, string> = Object.fromEntries(
  Object.entries(en).map(([key, value]) => [key, pseudoLocalize(value)]),
) as Record<MessageKey, string>

export const messages: Record<Locale, Record<MessageKey, string>> = {
  en,
  es,
  ar,
  'en-xa': pseudo,
}

function pseudoLocalize(value: string): string {
  const map: Record<string, string> = {
    a: 'å',
    A: 'Å',
    e: 'ē',
    E: 'Ē',
    i: 'ī',
    I: 'Ī',
    o: 'ō',
    O: 'Ō',
    u: 'ū',
    U: 'Ū',
    y: 'ȳ',
    Y: 'Ȳ',
  }
  return `[!! ${value.replace(/[AEOUIYaeouiy]/g, (ch) => map[ch] ?? ch)} !!]`
}
