import { useState } from 'react'
import flowExplorerSchema from './flowExplorerSchema.json'
import { describe, expect, test } from 'vitest'
import { fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { axe } from 'jest-axe'
import { FlowPlanBuilder } from '../routes/FlowPlanBuilder'
import type { FlowExplorerSchema, FlowQueryPlan } from '../api/flowExplorer'

// Generated by the control-plane registry; its Go drift test is authoritative.
const schema = flowExplorerSchema as FlowExplorerSchema

function Harness({ initial }: { initial?: FlowQueryPlan }) {
  const [plan, setPlan] = useState<FlowQueryPlan>(
    initial ?? { group_by: ['src_addr'], view: 'table', row_limit: 100, page_size: 100 },
  )
  return (
    <>
      <FlowPlanBuilder
        plan={plan}
        schema={schema}
        filters={[{ id: 'shared-filter', name: 'Shared safe filter' }]}
        onChange={(patch) => setPlan((current) => ({ ...current, ...patch }))}
      />
      <output data-testid="plan">{JSON.stringify(plan)}</output>
    </>
  )
}

describe('native flow plan controls', () => {
  test('offers all routing fields and keeps complete path and unknown ASN operands', () => {
    const path = JSON.stringify(['64500 '.repeat(65537) + '4294967295'])
    render(
      <Harness
        initial={{
          group_by: ['src_bgp_as_paths'],
          view: 'table',
          filter: {
            conditions: [
              { field: 'src_bgp_as_paths', op: 'eq', values: [path] },
              { field: 'dst_bgp_origin_as', op: 'eq', values: [''] },
            ],
          },
        }}
      />,
    )
    const picker = screen.getByLabelText('Group by dimension 1')
    for (const side of ['src', 'dst']) {
      for (const suffix of [
        'bgp_provenance',
        'bgp_prefix',
        'bgp_as_paths',
        'bgp_next_hop_as',
        'bgp_origin_as',
        'bgp_first_transit_as',
        'bgp_rpki',
      ]) {
        expect(picker.querySelector(`option[value="${side}_${suffix}"]`)).not.toBeNull()
      }
    }
    const operand = screen.getByLabelText('Condition 1.1 value 1')
    expect(operand).toHaveValue(path)
    expect(Number(operand.getAttribute('maxlength'))).toBeGreaterThan(path.length)
    expect(screen.getByLabelText('Condition 1.2 value 1')).toHaveValue('')
    fireEvent.change(operand, { target: { value: path + ' ' } })
    expect(JSON.parse(screen.getByTestId('plan').textContent).filter.conditions[0].values[0]).toBe(
      path + ' ',
    )
  })

  test('discloses retained and legacy dimension availability from the registry', async () => {
    const user = userEvent.setup()
    const coverageSchema: FlowExplorerSchema = {
      ...schema,
      fields: schema.fields.map((field) => ({
        ...field,
        rollup_available: field.name !== 'row_id',
        legacy_hourly_available: field.name === 'protocol',
      })),
    }
    render(
      <FlowPlanBuilder
        plan={{ group_by: ['protocol'], view: 'table' }}
        schema={coverageSchema}
        filters={[]}
        onChange={() => undefined}
      />,
    )
    await user.click(screen.getByText('Retained dimension coverage'))
    const retained = screen.getByText(/^Retained input fields:/)
    expect(retained).toHaveTextContent('protocol')
    expect(retained).not.toHaveTextContent('row id')
    expect(screen.getByText(/^Raw-only fields:/)).toHaveTextContent('row id')
    expect(screen.getByText(/^Older hourly schema fields:/)).toHaveTextContent(
      'Older hourly schema fields: protocol.',
    )
  })

  test('offers all eight dimensions on both axes and independent reach controls', async () => {
    const user = userEvent.setup()
    render(<Harness />)
    for (let i = 0; i < 7; i++)
      await user.click(screen.getByRole('button', { name: 'Add group by dimension' }))
    expect(screen.getByRole('button', { name: 'Add group by dimension' })).toBeDisabled()
    await user.selectOptions(screen.getByLabelText('Flow visualization'), 'matrix')
    for (let i = 0; i < 7; i++)
      await user.click(screen.getByRole('button', { name: 'Add matrix with dimension' }))
    expect(screen.getByRole('button', { name: 'Add matrix with dimension' })).toBeDisabled()
    expect(screen.getByLabelText('Matrix values per axis')).toHaveValue(15)
    await user.selectOptions(screen.getByLabelText('Flow visualization'), 'table')
    const rows = screen.getByLabelText('Selected detail groups')
    await user.clear(rows)
    await user.type(rows, '50000')
    const bucket = screen.getByLabelText('Bucket width (seconds)')
    await user.clear(bucket)
    await user.type(bucket, '604800')
    expect(JSON.parse(screen.getByTestId('plan').textContent).row_limit).toBe(50000)
    expect(JSON.parse(screen.getByTestId('plan').textContent).bucket_seconds).toBe(604800)
    await user.clear(bucket)
    await user.type(bucket, '2592000')
    expect(JSON.parse(screen.getByTestId('plan').textContent).bucket_seconds).toBe(2592000)
    await user.clear(bucket)
    await user.type(bucket, '1')
    expect(JSON.parse(screen.getByTestId('plan').textContent).bucket_seconds).toBe(1)
    expect(screen.getByLabelText('Plotted group series')).toHaveValue(40)
  })

  test('preserves complete selected detail counts while switching views', async () => {
    const user = userEvent.setup()
    render(
      <Harness
        initial={{ group_by: ['src_addr'], view: 'table', row_limit: 50001, page_size: 5000 }}
      />,
    )
    expect(screen.getByLabelText('Selected detail groups')).toHaveValue(50001)
    await user.selectOptions(screen.getByLabelText('Flow visualization'), 'line')
    expect(JSON.parse(screen.getByTestId('plan').textContent).row_limit).toBe(50001)
    expect(JSON.parse(screen.getByTestId('plan').textContent).page_size).toBe(5000)
    expect(screen.getByLabelText('Selected detail groups')).toHaveValue(50001)
    await user.selectOptions(screen.getByLabelText('Flow visualization'), 'table')
    expect(JSON.parse(screen.getByTestId('plan').textContent).row_limit).toBe(50001)
  })

  test('keeps exact operands, nested include/exclude and saved references', async () => {
    const user = userEvent.setup()
    render(<Harness />)
    await user.click(screen.getByRole('button', { name: 'Add condition to group 1' }))
    await user.selectOptions(screen.getByLabelText('Condition 1.1 field'), 'raw_bytes')
    await user.selectOptions(screen.getByLabelText('Condition 1.1 operator'), 'gt')
    await user.type(screen.getByLabelText('Condition 1.1 value 1'), '18446744073709551615')
    await user.selectOptions(screen.getByLabelText('Group 1 match'), 'any')
    await user.selectOptions(screen.getByLabelText('Group 1 inclusion'), 'exclude')
    await user.click(screen.getByRole('button', { name: 'Add saved filter to group 1' }))
    let path = '1'
    for (let depth = 1; depth < 5; depth++) {
      await user.click(screen.getByRole('button', { name: `Add nested group to ${path}` }))
      path += '.1'
    }
    expect(screen.getByRole('button', { name: `Add nested group to ${path}` })).toBeDisabled()
    const plan = JSON.parse(screen.getByTestId('plan').textContent)
    expect(plan.filter.conditions[0].values).toEqual(['18446744073709551615'])
    expect(plan.filter.mode).toBe('exclude')
    expect(plan.filter.match).toBe('any')
    expect(plan.filter.saved[0].id).toBe('shared-filter')
  })

  test('keeps the250th condition reachable through small DOM windows and bounds additions', async () => {
    const user = userEvent.setup()
    render(
      <Harness
        initial={{
          filter: {
            conditions: Array.from({ length: 250 }, () => ({
              field: 'raw_bytes',
              op: 'eq',
              values: ['1'],
            })),
          },
        }}
      />,
    )
    expect(screen.queryByLabelText('Condition 1.250 value 1')).not.toBeInTheDocument()
    for (let i = 0; i < 9; i++) await user.click(screen.getByText('Next entries in group 1'))
    expect(screen.getByLabelText('Condition 1.250 value 1')).toHaveValue('1')
    fireEvent.change(screen.getByLabelText('Condition 1.250 value 1'), {
      target: { value: '9007199254740993' },
    })
    const updated = JSON.parse(screen.getByTestId('plan').textContent).filter.conditions
    expect(updated[249].values).toEqual(['9007199254740993'])
    expect(updated[0].values).toEqual(['1'])
    expect(screen.getByRole('button', { name: 'Add condition to group 1' })).toBeDisabled()
  })

  test('has accessible labels and fieldsets', async () => {
    const { container } = render(<Harness />)
    expect(await axe(container)).toHaveNoViolations()
  })

  test.each([
    ['src_addr', 'cidr', '192.0.2.0/24', '198.51.100.0/24', '203.0.113.0/24'],
    ['src_addr', 'not_cidr', '192.0.2.0/24', '198.51.100.0/24', '203.0.113.0/24'],
    ['tcp_flag_names', 'has_any', 'SYN', 'ACK', 'RST'],
    ['tcp_flag_names', 'has_none', 'SYN', 'ACK', 'RST'],
  ])('edits every operand for the variadic %s %s operator', (field, op, first, second, third) => {
    render(
      <Harness initial={{ filter: { conditions: [{ field, op, values: [first, second] }] } }} />,
    )
    fireEvent.click(screen.getByText('Add value to condition 1.1'))
    fireEvent.change(screen.getByLabelText('Condition 1.1 value 3'), { target: { value: third } })
    expect(JSON.parse(screen.getByTestId('plan').textContent).filter.conditions[0].values).toEqual([
      first,
      second,
      third,
    ])
  })
})
